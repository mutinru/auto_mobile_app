import '../data/auth_service.dart';
import 'order_store.dart';

/// Один [OrderStore] на сессию входа (ревью №41). Экраны заказа после
/// действия подменяют заказ в списках через [OrderStore.replaceOrder] — это
/// видно только тем спискам, что живут в том же сторе. Поэтому стор заказов
/// берут только отсюда: и дом раздела, и профиль, и заказ из пуша или ленты.
///
/// Стор создаётся при первом обращении и сбрасывается, когда сессии больше
/// нет: выход, удаление аккаунта, истёкшая сессия. Новый вход идёт из
/// состояния «не вошёл», так что списки прошлого пользователя до него не
/// доживают. Признак — токен, а не профиль: после офлайн-старта профиля ещё
/// нет, а сессия уже есть.
class OrderSession {
  OrderSession(this._auth, this._create) {
    _auth.addListener(_onAuth);
  }

  final AuthService _auth;
  final OrderStore Function() _create;
  OrderStore? _store;

  /// Стор текущей сессии; при первом обращении — новый.
  OrderStore get store => _store ??= _create();

  /// Пока сессия поднимается с диска, стора ещё нет — сбрасывать нечего.
  void _onAuth() {
    if (!_auth.isAuthenticated) _drop();
  }

  /// Экраны прошлой сессии ещё могут уходить с анимацией, а их запросы —
  /// возвращаться: освобождённый стор их ответы молча пропускает.
  void _drop() {
    _store?.dispose();
    _store = null;
  }

  void dispose() {
    _auth.removeListener(_onAuth);
    _drop();
  }
}
